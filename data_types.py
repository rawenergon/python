""" Python operates on 7 Core data types some of them that we need
to know is "int = integers", "bool = Boolean", "Str = String" """


a = "adi"
print(type(a))
# OUTPUT = str 

b = True
print(type(b))
# OUTPUT = bool

c = 21
print(type(c))
# OUTPUT = int

d = 21.0
print(type(d))
# OUTPUT = float

# MORE ONE

e = ("Aditya","Abhi","Tanish")
print(type(e))
# OUTPUT = tuple

f = ["Aditya","Abhi","Tanish"]
print(type(f))
# OUTPUT = list

g = {"Name": "Aditya", "Age": 16}
print(type(g))
# OUTPUT = dict 
